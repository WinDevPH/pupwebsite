function esc(value) {
  return String(value).replaceAll('\\', '\\\\').replaceAll("'", "''")
}

const rows = events
  .map((event, index) => {
    const description = descriptions[event.id]
    return `  (
    '${esc(event.id)}',
    '${esc(event.kind)}',
    '${esc(event.title)}',
    ${description ? `'${esc(description)}'` : 'NULL'},
    '${event.start}',
    '${event.end}',
    ${index + 1},
    1
  )`
  })
  .join(',\n')

const sql = `-- Academic calendar events (A.Y. 2026–2027)
USE pup_col_sc;

CREATE TABLE IF NOT EXISTS calendar_events (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  slug VARCHAR(191) NOT NULL,
  kind ENUM('holiday', 'exam', 'enrollment', 'academic') NOT NULL DEFAULT 'academic',
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  is_published TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_calendar_events_slug (slug),
  KEY idx_calendar_events_dates (start_date, end_date),
  KEY idx_calendar_events_kind (kind),
  KEY idx_calendar_events_published (is_published, start_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO calendar_events
  (slug, kind, title, description, start_date, end_date, sort_order, is_published)
VALUES
${rows}
ON DUPLICATE KEY UPDATE
  kind = VALUES(kind),
  title = VALUES(title),
  description = VALUES(description),
  start_date = VALUES(start_date),
  end_date = VALUES(end_date),
  sort_order = VALUES(sort_order),
  is_published = VALUES(is_published);
`

